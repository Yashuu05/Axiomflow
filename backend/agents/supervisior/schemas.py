from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field, field_validator
from agents.policies_ethics import PolicyCheckResult

class SufficiencyAssessment(BaseModel):
    """
    Assessment of whether the user request contains sufficient parameters
    to execute the requested tools without ambiguity and complies with policies.
    """
    is_sufficient: bool = Field(
        ...,
        description="True if user request contains all necessary details for the requested services and complies with policies. False if critical parameter missing or policy violated."
    )
    missing_fields: Optional[List[str]] = Field(
        default=None,
        description="List of parameter names missing from user prompt (e.g. 'receiver_email', 'meeting_time')"
    )
    questions: Optional[List[str]] = Field(
        default=None,
        description="Numbered, complete list of questions to ask user simultaneously. Must be empty if is_sufficient is True."
    )
    reasoning: Optional[str] = Field(
        default=None,
        description="Concise rationale for sufficiency assessment"
    )
    policy_check: Optional[PolicyCheckResult] = Field(
        default=None,
        description="Outcome of safety, ethics, and scope evaluation"
    )

    @field_validator("missing_fields", "questions", mode="before")
    def default_none_to_empty(cls, v):
        return v if v is not None else []

class StepProposal(BaseModel):
    """
    Represents an atomic, validated execution step produced by the Planning/Supervisor Agent.
    """
    id: str = Field(..., description="Unique step identifier, e.g. 'step_1', 'step_2'")
    capability: str = Field(
        ...,
        description="The approved capability name, e.g. 'calendar.check_availability', 'calendar.create_event', 'content.draft_email', 'gmail.send'"
    )
    description: str = Field(..., description="Clear explanation of the purpose of this step")
    parameters: Dict[str, Any] = Field(
        default_factory=dict,
        description="Key arguments extracted from user request for this capability"
    )
    depends_on: List[str] = Field(
        default_factory=list,
        description="List of step IDs that must finish successfully before this step executes"
    )
    risk: Literal["read_only", "no_external_side_effect", "external_side_effect"] = Field(
        default="read_only",
        description="Risk category of this operation"
    )
    requires_approval: bool = Field(
        default=False,
        description="Whether human confirmation is mandatory before performing this step"
    )

class SupervisorPlan(BaseModel):
    """
    Complete structured output schema generated by the Planning/Supervisor Agent.
    """
    intent: str = Field(..., description="Concise interpretation of user business intent")
    goal: str = Field(..., description="High-level goal to be achieved")
    identified_services: List[str] = Field(
        default_factory=list,
        description="List of Google services involved, e.g. ['calendar', 'gmail']"
    )
    steps: List[StepProposal] = Field(
        default_factory=list,
        description=(
            "Complete, ordered sequence of execution steps needed to fulfill the entire user request. "
            "For requests involving both a meeting and an email, you MUST include: "
            "1. calendar step (calendar.create_event or calendar.check_availability), "
            "2. drafting step (content.draft_email), "
            "3. sending step (gmail.send depending on content.draft_email)."
        )
    )
    clarification_needed: Optional[str] = Field(
        default=None,
        description="Question for user if essential info (like recipient email or missing dates) cannot be inferred"
    )
    reasoning: Optional[str] = Field(
        default=None,
        description="Brief explanation of why these steps and dependencies were chosen"
    )
    policy_check: Optional[PolicyCheckResult] = Field(
        default=None,
        description="Result of safety, ethics, and capability guardrail evaluation"
    )
    is_policy_rejected: bool = Field(
        default=False,
        description="True if the request was red-flagged and rejected under policies & ethics"
    )
    refusal_message: Optional[str] = Field(
        default=None,
        description="Polite user-facing refusal message terminating execution"
    )
